"""Bounded official-source adapters with strict dimensional checks and injectable transport."""

import csv
import io
import json
import time
from collections.abc import Callable
from datetime import UTC, datetime
from email.utils import parsedate_to_datetime
from typing import Any
from urllib.error import HTTPError, URLError
from urllib.parse import urlencode
from urllib.request import Request, urlopen

from luxrisk.catalog import country_code, indicator_spec
from luxrisk.models import Indicator, JsonObject, Observation, SourceBatch, period_end, utc_now

type Fetcher = Callable[[str], bytes]
MAX_BYTES: int = 8_000_000


class SourceError(RuntimeError):
    """Signal transport or provider-contract failure without publishing a partial batch."""


def get_bytes(url: str) -> bytes:
    """Retrieve a bounded HTTPS response from an approved statistical provider.

    Args:
        url: Eurostat or ECB URL generated by an adapter.

    Returns:
        Exact response bytes for parsing and a reproducible SHA-256 digest.

    Raises:
        SourceError: Request fails, exceeds 8 MB, redirects off-provider or requires a long retry.

    Side effects:
        Performs up to two HTTP requests, with 20-second timeouts and at most 2 seconds of delay.
        Honors Retry-After; a longer requested delay stops this attempt instead of retrying early.

    """
    allowed: tuple[str, ...] = (
        "https://ec.europa.eu/eurostat/",
        "https://data-api.ecb.europa.eu/",
    )
    if not url.startswith(allowed):
        raise SourceError("Only the official source endpoints are allowed")
    for attempt in range(2):
        try:
            request: Request = Request(
                url, headers={"User-Agent": "LuxRisk/0.1 source-audited portfolio"}
            )
            with urlopen(request, timeout=20) as response:
                if not response.url.startswith(allowed):
                    raise SourceError("Unexpected provider redirect")
                payload: bytes = response.read(MAX_BYTES + 1)
            if not payload or len(payload) > MAX_BYTES:
                raise SourceError("Empty response or response larger than 8 MB")
            return payload
        except HTTPError as exc:
            delay: float = 1.0
            retry: str | None = exc.headers.get("Retry-After")
            if retry:
                try:
                    delay = float(retry)
                except ValueError:
                    try:
                        delay = (parsedate_to_datetime(retry) - datetime.now(UTC)).total_seconds()
                    except (ValueError, TypeError) as bad_header:
                        raise SourceError("Invalid Retry-After header") from bad_header
            if attempt == 1 or exc.code not in {429, 500, 502, 503, 504} or delay > 2:
                raise SourceError(f"Source returned HTTP {exc.code}; retry later") from exc
            time.sleep(max(0.0, delay))
        except (URLError, TimeoutError, OSError) as exc:
            raise SourceError(f"Source could not be reached: {exc}") from exc
    raise SourceError("Request attempts exhausted")


def _numeric(value: Any) -> float | None:
    """Parse a source number while preserving missingness and rejecting boolean values.

    Args:
        value: A provider number, empty string or null.

    Returns:
        A float, or None for a missing cell. Observation validates finiteness.

    Raises:
        ValueError: A supplied nonmissing cell is not numeric.

    Side effects:
        None; missing values are never replaced with zero.

    """
    if value is None or value == "":
        return None
    if isinstance(value, bool):
        raise ValueError("Boolean observation is not a statistical value")
    return float(value)


class EurostatConnector:
    """Own official JSON-stat retrieval and normalization; keep no database state."""

    def __init__(self, fetch: Fetcher = get_bytes) -> None:
        """Configure transport without making a source request.

        Args:
            fetch: URL-to-bytes function; tests inject small authored fixtures.

        Returns:
            None; stores a callable for collect.

        Side effects:
            None.

        """
        self.fetch: Fetcher = fetch

    def collect(self, indicator: str, country: str, start: str, end: str) -> SourceBatch:
        """Fetch one country/indicator slice within an explicit period window.

        Args:
            indicator: A Eurostat catalogue ID.
            country: Configured ISO country code.
            start: First month or quarter, matching the indicator frequency.
            end: Last period, inclusive; maximum window is 20 years.

        Returns:
            Exact source bytes, retrieval timestamp, URL and validated rows.

        Raises:
            ValueError: Catalogue, country, window or observation values are invalid.
            SourceError: Transport or provider dimensions do not match the request.

        Side effects:
            One bounded request (transport may retry); no filesystem writes.

        """
        spec: Indicator = indicator_spec(indicator)
        code: str = country_code(country)
        validate_window(spec, start, end)
        if spec.provider != "Eurostat":
            raise ValueError("Choose a Eurostat indicator for this adapter")
        params: dict[str, str] = dict(spec.filters)
        params.update(geo=code, lang="EN", sinceTimePeriod=start, untilTimePeriod=end)
        url: str = (
            "https://ec.europa.eu/eurostat/api/dissemination/statistics/1.0/data/"
            + spec.dataset
            + "?"
            + urlencode(params)
        )
        payload: bytes = self.fetch(url)
        rows: tuple[Observation, ...] = self.normalize(payload, spec, code)
        return SourceBatch(spec.id, code, url, utc_now(), payload, rows)

    def normalize(self, payload: bytes, spec: Indicator, country: str) -> tuple[Observation, ...]:
        """Decode one singleton-series JSON-stat cube independently of dimension order.

        Args:
            payload: Original UTF-8 JSON bytes.
            spec: Catalogue contract whose exact dimensions must be present.
            country: Requested country; a different returned geography is rejected.

        Returns:
            Sorted observations, including absent cells as explicit None values and source flags.

        Raises:
            SourceError: JSON, shape, selectors or time positions violate the source contract.
            ValueError: A nonmissing number or period cannot be validated.

        Side effects:
            None; preserves payload and status flags.

        """
        try:
            data: JsonObject = json.loads(payload)
            ids: list[str] = data["id"]
            sizes: list[int] = data["size"]
            dimensions: JsonObject = data["dimension"]
            expected: dict[str, str] = dict(spec.filters) | {"geo": country}
            if set(ids) != set(expected) | {"time"} or len(ids) != len(sizes):
                raise SourceError("Unexpected JSON-stat dimensions; inspect the provider schema")
            for name, size in zip(ids, sizes, strict=True):
                category: JsonObject = dimensions[name]["category"]["index"]
                if name != "time" and (size != 1 or category != {expected[name]: 0}):
                    raise SourceError(f"Source selector differs or is unavailable: {name}")
            periods: JsonObject = dimensions["time"]["category"]["index"]
            if (
                sorted(periods.values()) != list(range(len(periods)))
                or len(periods) != sizes[ids.index("time")]
            ):
                raise SourceError("Invalid time positions")
            values: Any = data.get("value", {})
            statuses: Any = data.get("status", {})
            rows: list[Observation] = []
            for period, position in sorted(periods.items()):
                value: Any = (
                    values.get(str(position)) if isinstance(values, dict) else values[position]
                )
                status: Any = (
                    statuses.get(str(position), "")
                    if isinstance(statuses, dict)
                    else statuses[position]
                )
                rows.append(
                    Observation(country, spec.id, period, _numeric(value), str(status or ""))
                )
            if not rows or all(row.value is None for row in rows):
                raise SourceError("No usable values returned for this country and window")
            return tuple(rows)
        except (KeyError, TypeError, IndexError, json.JSONDecodeError, UnicodeDecodeError) as exc:
            raise SourceError("Malformed Eurostat JSON-stat response") from exc


class ECBConnector:
    """Own the ECB monthly USD-per-EUR context series; entity EA is explicitly shared."""

    def __init__(self, fetch: Fetcher = get_bytes) -> None:
        """Configure an injectable URL-to-bytes transport.

        Args:
            fetch: Bounded HTTP function or an authored fixture reader.

        Returns:
            None; saves only the transport callable.

        Side effects:
            No network, database or filesystem access.

        """
        self.fetch: Fetcher = fetch

    def collect(self, start: str, end: str) -> SourceBatch:
        """Fetch the monthly average USD-per-EUR exchange-rate slice.

        Args:
            start: First month, inclusive.
            end: Last month, inclusive; at most 20 years after start.

        Returns:
            An auditable SourceBatch with country/entity EA, never a national FX series.

        Raises:
            ValueError: Period window is invalid.
            SourceError: Request or CSV contract fails.

        Side effects:
            One bounded official-source request; writes no files.

        """
        spec: Indicator = indicator_spec("eurusd")
        validate_window(spec, start, end)
        url: str = (
            "https://data-api.ecb.europa.eu/service/data/"
            + spec.dataset
            + "?"
            + urlencode({"format": "csvdata", "startPeriod": start, "endPeriod": end})
        )
        payload: bytes = self.fetch(url)
        return SourceBatch(spec.id, "EA", url, utc_now(), payload, self.normalize(payload))

    def normalize(self, payload: bytes) -> tuple[Observation, ...]:
        """Validate ECB selectors and decode its observation CSV.

        Args:
            payload: UTF-8 ECB CSV bytes; BOM is accepted.

        Returns:
            Sorted monthly rows with source flags and explicit missing values.

        Raises:
            SourceError: Columns, selectors, frequency or usable observations are missing.
            ValueError: Numeric or calendar validation fails.

        Side effects:
            None; rows are not persisted here.

        """
        try:
            reader: csv.DictReader[str] = csv.DictReader(io.StringIO(payload.decode("utf-8-sig")))
            required: set[str] = {"TIME_PERIOD", "OBS_VALUE", "UNIT_MULT", "UNIT"} | dict(
                indicator_spec("eurusd").filters
            ).keys()
            if not required.issubset(reader.fieldnames or []):
                raise SourceError("ECB CSV columns changed")
            rows: list[Observation] = []
            for raw in reader:
                if any(raw.get(key) != value for key, value in indicator_spec("eurusd").filters):
                    raise SourceError("ECB series selectors differ from the catalogue")
                if raw["UNIT"] != "USD" or raw["UNIT_MULT"] != "0":
                    raise SourceError("Unexpected ECB unit or scaling")
                row: Observation = Observation(
                    "EA",
                    "eurusd",
                    raw["TIME_PERIOD"],
                    _numeric(raw["OBS_VALUE"]),
                    raw.get("OBS_STATUS", ""),
                )
                if "Q" in row.period or (row.value is not None and row.value <= 0):
                    raise SourceError("ECB monthly reference rates must be positive")
                rows.append(row)
            if not rows or all(row.value is None for row in rows):
                raise SourceError("No usable ECB values returned")
            return tuple(sorted(rows, key=lambda row: row.period))
        except UnicodeDecodeError as exc:
            raise SourceError("ECB response is not UTF-8 CSV") from exc


def validate_window(spec: Indicator, start: str, end: str) -> None:
    """Check frequency, order and bounded size before source access.

    Args:
        spec: Indicator contract defining M or Q.
        start: Inclusive first period.
        end: Inclusive final period.

    Returns:
        None when both labels match the required frequency and a valid window.

    Raises:
        ValueError: Frequencies differ, dates are reversed or window exceeds 20 years.

    Side effects:
        None.

    """
    first = period_end(start)
    last = period_end(end)
    if any(("Q" in label) != (spec.frequency == "Q") for label in (start, end)):
        raise ValueError(f"{spec.id} requires {spec.frequency} periods")
    if first > last or last.year - first.year > 20:
        raise ValueError("Use an ordered window no longer than 20 years")
